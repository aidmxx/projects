# Test report content generation
test_that("report content includes summary statistics", {
  # Generate report content with summary stats
  generate_report_content <- function(data, chart_types) {
    content <- "# Livestock Dashboard Report\n\n"
    content <- paste0(content, "## Summary Statistics\n\n")
    
    # Add summary stats
    content <- paste0(content, "- **Total Records**: ", nrow(data), "\n")
    content <- paste0(content, "- **Date Range**: ", min(data$date), " to ", max(data$date), "\n")
    content <- paste0(content, "- **Average Weight**: ", round(mean(data$weight), 2), " kg\n")
    content <- paste0(content, "- **Average Feed Intake**: ", round(mean(data$feed_intake), 2), " kg/day\n")
    content <- paste0(content, "- **Average Methane**: ", round(mean(data$methane), 2), " g/day\n\n")
    
    # Add chart information
    if (length(chart_types) > 0) {
      content <- paste0(content, "## Charts Included\n\n")
      for (chart in chart_types) {
        content <- paste0(content, "- ", chart, "\n")
      }
    }
    
    return(content)
  }
  
  report_content <- generate_report_content(test_report_data, test_chart_types)
  
  expect_true(is.character(report_content))
  expect_true(grepl("Livestock Dashboard Report", report_content))
  expect_true(grepl("Summary Statistics", report_content))
  expect_true(grepl("Total Records", report_content))
  expect_true(grepl("7", report_content))  # Number of records
  expect_true(grepl("Charts Included", report_content))
  expect_true(grepl("Weight Trend", report_content))
})

