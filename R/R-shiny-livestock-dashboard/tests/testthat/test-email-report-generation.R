# Test error handling in report generation
test_that("report generation handles data errors gracefully", {
  # Test with corrupted data
  corrupted_data <- data.frame(
    date = c("invalid_date", "2024-01-02", "2024-01-03"),
    weight = c("not_a_number", 455, 460)
  )
  
  safe_report_generation <- function(data) {
    tryCatch({
      content <- "# Report\n\n"
      
      # Try to process dates
      if ("date" %in% names(data)) {
        valid_dates <- tryCatch({
          suppressWarnings(as.Date(data$date))
        }, error = function(e) {
          return(NA)
        })
        
        if (!all(is.na(valid_dates))) {
          content <- paste0(content, "- Valid dates: ", sum(!is.na(valid_dates)), "\n")
        } else {
          content <- paste0(content, "- Date processing failed\n")
        }
      }
      
      # Try to process numeric data
      if ("weight" %in% names(data)) {
        numeric_weights <- tryCatch({
          suppressWarnings(as.numeric(data$weight))
        }, error = function(e) {
          return(NA)
        })
        
        if (!all(is.na(numeric_weights))) {
          content <- paste0(content, "- Valid weights: ", sum(!is.na(numeric_weights)), "\n")
        } else {
          content <- paste0(content, "- Weight processing failed\n")
        }
      }
      
      return(content)
    }, error = function(e) {
      return("# Report\n\nError generating report: Unable to process data")
    })
  }
  
  result <- safe_report_generation(corrupted_data)
  
  expect_true(is.character(result))
  expect_true(grepl("Report", result))
  expect_false(grepl("Error generating report", result))
})

