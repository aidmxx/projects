# Test report content with missing values
test_that("report content handles missing values", {
  # Data with missing values
  data_with_na <- data.frame(
    date = seq(as.Date("2024-01-01"), as.Date("2024-01-05"), by = "day"),
    weight = c(450, NA, 460, 465, NA),
    feed_intake = c(8.5, 8.7, NA, 9.1, 9.3)
  )
  
  handle_missing_values <- function(data) {
    content <- "# Report\n\n"
    
    # Handle missing weights
    if ("weight" %in% names(data)) {
      valid_weights <- data$weight[!is.na(data$weight)]
      if (length(valid_weights) > 0) {
        content <- paste0(content, "- Average Weight: ", round(mean(valid_weights), 2), " kg (", length(valid_weights), " valid records)\n")
      } else {
        content <- paste0(content, "- Weight: No valid data\n")
      }
    }
    
    # Handle missing feed intake
    if ("feed_intake" %in% names(data)) {
      valid_feed <- data$feed_intake[!is.na(data$feed_intake)]
      if (length(valid_feed) > 0) {
        content <- paste0(content, "- Average Feed Intake: ", round(mean(valid_feed), 2), " kg/day (", length(valid_feed), " valid records)\n")
      } else {
        content <- paste0(content, "- Feed Intake: No valid data\n")
      }
    }
    
    return(content)
  }
  
  result <- handle_missing_values(data_with_na)
  
  expect_true(grepl("Average Weight: 458.33 kg \\(3 valid records\\)", result))
  expect_true(grepl("Average Feed Intake: 8.9 kg/day \\(4 valid records\\)", result))
})
