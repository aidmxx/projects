# Test email recipient validation
test_that("email recipient validation works", {
  validate_recipient <- function(email) {
    if (is.null(email) || !is.character(email) || length(email) != 1) {
      return(FALSE)
    }
    if (email == "" || !grepl("^[^@]+@[^@]+\\.[^@]+$", email)) {
      return(FALSE)
    }
    return(TRUE)
  }
  
  # Valid emails
  valid_emails <- c(
    "user@example.com",
    "test.user@domain.co.uk",
    "user+tag@example.org"
  )
  
  for (email in valid_emails) {
    expect_true(validate_recipient(email))
  }
  
  # Invalid emails
  invalid_emails <- c(
    "invalid-email",
    "@example.com",
    "test@",
    ""
  )
  
  for (email in invalid_emails) {
    expect_false(validate_recipient(email))
  }
  
  # Test vector input separately
  expect_false(validate_recipient(c("user1@example.com", "user2@example.com")))
  
  # Test NULL separately
  expect_false(validate_recipient(NULL))
})

